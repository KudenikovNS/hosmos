#!/usr/bin/env node
/**
 * ONE-OFF GENERATOR — emits `drizzle/0018_metric_catalog_title_sl.sql` from
 * `src/server/db/seed-data/vsme-metrics.sl.json` (metric_key → Slovene title).
 * The JSON is the reviewable source; the migration is its rendering. Rerun
 * after the methodologist's review changes a title:
 *
 *   node scripts/gen-metric-titles-sl.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const titles = JSON.parse(
  readFileSync(
    path.join(REPO, "src/server/db/seed-data/vsme-metrics.sl.json"),
    "utf8",
  ),
);
const catalogue = JSON.parse(
  readFileSync(
    path.join(REPO, "src/server/db/seed-data/vsme-metrics.json"),
    "utf8",
  ),
);
const keys = catalogue.map((m) => m.metric_key);
for (const key of keys)
  if (!titles[key]) throw new Error(`no Slovene title for ${key}`);
for (const key of Object.keys(titles))
  if (!keys.includes(key)) throw new Error(`unknown key ${key}`);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = keys.map((k) => `  (${q(k)}, ${q(titles[k])})`).join(",\n");
const sql = `-- 0018_metric_catalog_title_sl.sql — SLOVENE TITLES FOR THE 141 DATAPOINTS.
--
-- GENERATED by \`scripts/gen-metric-titles-sl.mjs\` from
-- \`src/server/db/seed-data/vsme-metrics.sl.json\`. DO NOT EDIT BY HAND — edit
-- the JSON (the reviewable source) and rerun the generator.
--
-- The disclosure HEADINGS (B1–B11, C1–C9) came from the official Slovene text
-- of Recommendation (EU) 2025/1710 in 0017. The DATAPOINT titles below are a
-- translation of the catalogue's English (\`title_en\`) into Slovene using that
-- text's terminology (emisije TGP, obseg 1/2/3, delovna sila, podjetje, ki
-- poroča). They are a working translation for the pilot and are flagged for
-- the methodologist's review (\`docs/plan-2026-09.md\`, партия 4.2); the
-- readiness screen and the renderer fall back to \`title_en\` when a title is
-- NULL, so a later correction is a data change, not a code change.
--
-- Idempotent: an UPDATE by primary key; a re-run rewrites the same values.

UPDATE metric_catalog SET title_sl = v.title
FROM (VALUES
${rows}
) AS v(metric_key, title)
WHERE metric_catalog.metric_key = v.metric_key;
`;
writeFileSync(path.join(REPO, "drizzle/0018_metric_catalog_title_sl.sql"), sql);
console.log(
  `wrote drizzle/0018_metric_catalog_title_sl.sql: ${keys.length} titles`,
);
