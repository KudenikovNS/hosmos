#!/bin/bash
# hosmos: жнец осиротевших Next-воркеров.
#
# ЗАЧЕМ. Под Passenger/LiteSpeed воркеры Next переживают рестарт: старый процесс
# ждёт закрытия keep-alive соединений, которых LiteSpeed не закрывает, и остаётся
# висеть. За сутки их набирается достаточно, чтобы упереться в NPROC=100 — и
# тогда аккаунт не может породить НИ ОДНОГО процесса: не открывается терминал
# cPanel, не строится снимок ресурсов, rsync из CI рвётся на нулевом байте, а
# SSH отваливается с `Broken pipe` сразу после handshake. Сайт при этом отдаёт
# 503, и вытащить себя изнутри аккаунт уже не может — чтобы убить процесс, нужен
# процесс. Разово это лечится только обращением к хостеру.
#
# КАК ОТЛИЧИТЬ ПРОТУХШИЙ ВОРКЕР ОТ ЖИВОГО — по РОДИТЕЛЮ, а не по возрасту.
# Возраст бесполезен: у здорового приложения с долгим аптаймом живой воркер тоже
# старый. А вот замер на живом проде показал, что все воркеры одного поколения
# имеют общего родителя — агента Passenger:
#
#     PID      PPID     ETIME    CMD
#     1542871  1534054  05:55    next-server (v16.2.10)
#     1542903  1534054  05:53    next-server (v16.2.10)
#
# Когда агент перезапускается, его старые дети либо остаются висеть на прежнем
# (уже мёртвом) PPID, либо усыновляются init'ом (PPID=1). И то и другое означает
# «поколение сменилось, а этот не ушёл» — то есть ровно тот случай, который
# набивает NPROC. Родитель САМОГО СВЕЖЕГО воркера принимается за текущее
# поколение; всё, что не его дети, — под нож.
#
# СЧЁТЧИК ОСТАЁТСЯ СТРАХОВКОЙ на случай, если поколение одно, а воркеров всё
# равно неприлично много (утечка внутри поколения): тогда оставляем KEEP самых
# свежих. Худшее при ошибке любого из двух правил — Passenger поднимет воркер на
# следующем запросе, то есть одна медленная загрузка страницы. Это несравнимо
# дешевле, чем упёршийся в потолок аккаунт.
#
# СНАЧАЛА TERM, ПОТОМ KILL. `NEXT_MANUAL_SIG_HANDLE=1` снимает с Next его
# обработчик SIGTERM, так что штатный сигнал должен убивать процесс сразу. Если
# не убил за GRACE секунд — значит именно этот случай мы и ловим, и добиваем
# SIGKILL. Порядок важен: KILL без TERM не даёт процессу закрыть соединения.
#
# УСТАНОВКА (на сервере, вне hosmos/ — деплой синхронизируется с --delete):
#   mkdir -p ~/bin && cp reap-workers.sh ~/bin/ && chmod +x ~/bin/reap-workers.sh
#   cron:  */10 * * * * /home/helphub/bin/reap-workers.sh >/dev/null 2>&1
set -u

KEEP="${REAP_KEEP:-2}"        # сколько самых свежих воркеров не трогать
GRACE="${REAP_GRACE:-5}"      # сколько секунд ждать после TERM
PATTERN='next-serve[r]'       # скобки: чтобы не совпасть с собственной строкой

# Все воркеры как «PID PPID», старые первыми (сортировка по времени старта).
#
# БЕЗ process substitution `< <(…)`: на этом хостинге CageFS не отдаёт /dev/fd,
# и `mapfile < <(…)` падает с «/dev/fd/63: No such file or directory». Под cron
# это падение было бы молчаливым — поймано только ручным прогоном на сервере.
# Здесь command substitution плюс here-string, которым /dev/fd не нужен.
raw=$(pgrep -u "$USER" -f "$PATTERN" 2>/dev/null \
      | xargs -r ps -o pid=,ppid=,lstart= -p 2>/dev/null \
      | sort -k3 | awk '{print $1" "$2}')

rows=()
if [ -n "$raw" ]; then
  while IFS= read -r line; do
    [ -n "$line" ] && rows+=("$line")
  done <<< "$raw"
fi

total=${#rows[@]}
if [ "$total" -eq 0 ]; then echo "reap: воркеров нет"; exit 0; fi

# Текущее поколение = родитель самого свежего воркера (последняя строка).
current_ppid=$(echo "${rows[-1]}" | awk '{print $2}')

doomed=()
same_gen=()
for row in "${rows[@]}"; do
  pid=${row%% *}; ppid=${row##* }
  if [ "$ppid" = "$current_ppid" ]; then same_gen+=("$pid"); else doomed+=("$pid"); fi
done

[ ${#doomed[@]} -gt 0 ] &&
  echo "reap: чужое поколение (PPID != $current_ppid): ${doomed[*]}"

# Страховка: даже внутри живого поколения оставляем не больше KEEP свежих.
if [ ${#same_gen[@]} -gt "$KEEP" ]; then
  extra=("${same_gen[@]:0:$((${#same_gen[@]}-KEEP))}")
  echo "reap: в текущем поколении ${#same_gen[@]} воркеров, оставляем $KEEP — лишние: ${extra[*]}"
  doomed+=("${extra[@]}")
fi

if [ ${#doomed[@]} -eq 0 ]; then
  echo "reap: $total воркеров, все одного живого поколения — чистить нечего"
  exit 0
fi
echo "reap: воркеров $total, гасим ${#doomed[@]}"

kill -TERM "${doomed[@]}" 2>/dev/null
sleep "$GRACE"

# Кто пережил TERM — тот и есть протухший воркер, ради которого всё затевалось.
survivors=()
for p in "${doomed[@]}"; do kill -0 "$p" 2>/dev/null && survivors+=("$p"); done

if [ ${#survivors[@]} -gt 0 ]; then
  echo "reap: пережили TERM (${#survivors[@]}): ${survivors[*]} — добиваем KILL"
  kill -KILL "${survivors[@]}" 2>/dev/null
else
  echo "reap: все ${#doomed[@]} умерли по TERM"
fi

echo "reap: осталось $(pgrep -u "$USER" -f "$PATTERN" 2>/dev/null | wc -l)"
