/**
 * `IN ('a','b',…)` rendered from a T1.1 enum constant, so a CHECK never
 * re-types the values by hand (§0.8: the few CHECKed columns are lifecycle
 * columns and structural discriminators; the domain lists stay free text).
 * The values are compile-time constants from `@/shared/enums` — nothing user
 * supplied ever reaches `sql.raw` here.
 */
const inList = (values: readonly string[]) =>
  sql.raw(`(${values.map((v) => `'${v}'`).join(",")})`);

