/**
 * Drizzle schema — application tables (public schema).
 *
 * Originally a 1:1 port of the pre-drizzle Supabase baseline for the 16 tables
 * the end-user app read/wrote; that migration tree was deleted in T3.9 together
 * with the five legacy tables it created (`drizzle/0005_drop_legacy.sql`), and
 * `drizzle/0000_baseline.sql` has been the sole authoritative DDL since.
 * Fidelity notes:
 *
 * - PKs use app-generated UUIDs (`crypto.randomUUID()` via `.$defaultFn`) rather
 *   than `gen_random_uuid()` / `defaultRandom()` — works on any Postgres version
 *   independent of pgcrypto (PG-PLAN decision 2026-07-14).
 * - NUMERIC columns map to `string` (Drizzle default) — never real/double, to
 *   preserve precision of monetary/factor values (PG-IMPL-SPEC ОВ-C).
 * - CHECK constraints are expressed as `check(name, sql\`...\`)` keeping columns
 *   as TEXT+CHECK 1:1 with the baseline — not pgEnum.
 *
 * Also included (added T-5, §3.2): the better-auth tables (user/session/account/
 * verification) with **uuid** id columns (`crypto.randomUUID()`, generated by the
 * app / better-auth `advanced.database.generateId`) instead of better-auth's
 * default `text` ids — so the FK `profiles.id → user.id` is uuid→uuid and user
 * import can preserve the original UUIDs. Field shapes are 1:1 with better-auth
 * 1.6.23's core schema (@better-auth/core getAuthTables); only the id/userId types
 * (uuid) and timestamp columns (timestamptz) deviate. JS property keys keep the
 * better-auth field names (camelCase) — the drizzleAdapter resolves columns by
 * that key, not by SQL column name — while SQL column names are snake_case to
 * match the rest of this file.
 *
 * NOT included here (by design): admin tables (admin_users/…) — deferred per ОВ-A.
 * RLS / auth.uid() / triggers are not table DDL and are not ported (isolation
 * lives in the API layer).
 */
